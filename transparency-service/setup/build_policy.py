"""Assemble the per-artefact-type Rego fragments into one ledger policy and the
``set_scitt_configuration`` proposal document.

The SCITT CCF ledger evaluates a single ``policyRego`` per instance. We compose
the three per-type fragments (each of which pins its own did:x509 trust anchor
and contributes an ``allow if ...`` rule) into one ``package policy`` with a
default-deny and a shared error message. The registration therefore satisfies
whichever single artefact-type rule matches -- exactly one rule matches per
statement because the artefact type is selected by the signing EKU in the issuer.
"""

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from tscli.constants import artefact_type_names  # noqa: E402

POLICY_DIR = REPO_ROOT / "transparency-service" / "policies"
DEFAULT_IDENTITIES = REPO_ROOT / "transparency-service" / "identities"

HEADER = """# GENERATED by build_policy.py -- do not edit by hand.
# Edit the per-type fragments in transparency-service/policies/ and rebuild.
package policy

import future.keywords

default allow := false
"""

FOOTER = """
# Catch-all only when the content-type matches no known artefact type; per-type
# fragments above emit the specific unmet-term reasons otherwise.
errors contains "Registration denied: unrecognised artefact content-type, or policy not satisfied." if {
	not allow
	not known_cty
}
"""


def placeholder_for(type_name: str) -> str:
    return f"__{type_name.upper()}_ISSUER__"


def build(identities_dir: Path) -> str:
    issuers = json.loads((identities_dir / "issuers.json").read_text())["issuers"]
    parts = [HEADER]
    for type_name in artefact_type_names():
        fragment = (POLICY_DIR / f"{type_name}.rego").read_text()
        issuer = issuers[type_name]
        fragment = fragment.replace(placeholder_for(type_name), issuer)
        # Strip the standalone comment header lines to keep the merged policy tidy;
        # keep inline extension-point comments.
        parts.append(f"\n# ----- artefact type: {type_name} -----\n{fragment}")
    parts.append(FOOTER)
    return "\n".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--identities-dir", type=Path, default=DEFAULT_IDENTITIES)
    parser.add_argument(
        "--out-policy",
        type=Path,
        default=DEFAULT_IDENTITIES / "policy.rego",
        help="Where to write the merged Rego policy (for inspection).",
    )
    parser.add_argument(
        "--out-config",
        type=Path,
        default=DEFAULT_IDENTITIES / "configuration.json",
        help="Where to write the set_scitt_configuration proposal body.",
    )
    parser.add_argument(
        "--allow-unauthenticated",
        action="store_true",
        default=True,
        help="Allow unauthenticated submissions (default for virtual-mode dev).",
    )
    args = parser.parse_args()

    policy = build(args.identities_dir)
    args.out_policy.write_text(policy)

    config = {
        "authentication": {"allowUnauthenticated": args.allow_unauthenticated},
        "policy": {"policyRego": policy},
    }
    args.out_config.write_text(json.dumps(config, indent=2) + "\n")
    print(f"Wrote merged policy to {args.out_policy}")
    print(f"Wrote configuration proposal to {args.out_config}")


if __name__ == "__main__":
    main()
